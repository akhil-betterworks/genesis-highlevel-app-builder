#!/usr/bin/env node
/**
 * Generates per-package env files from the root .env so there is one source of truth.
 *   functions/.env          non-secret params (committed shape, ignored values)
 *   functions/.secret.local secrets for the Functions emulator (never deployed)
 *   frontend/.env.local     Vite public config
 * Idempotent: keeps an existing TOKEN_ENCRYPTION_KEY so stored HL tokens stay decryptable.
 */
import { randomBytes } from 'node:crypto'
import { existsSync, readFileSync, writeFileSync, appendFileSync } from 'node:fs'
import { resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const envPath = resolve(root, '.env')
if (!existsSync(envPath)) {
  console.error('Missing .env — copy .env.example to .env and fill it in.')
  process.exit(1)
}

const env = Object.fromEntries(
  readFileSync(envPath, 'utf8')
    .split('\n')
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith('#') && l.includes('='))
    .map((l) => {
      const i = l.indexOf('=')
      return [l.slice(0, i).trim(), l.slice(i + 1).trim().replace(/^["']|["']$/g, '')]
    }),
)
const pick = (...keys) => keys.map((k) => env[k]).find(Boolean) ?? ''

const required = {
  VITE_FIREBASE_PROJECT_ID: pick('VITE_FIREBASE_PROJECT_ID'),
  HL_CLIENT_ID: pick('HL_CLIENT_ID', 'HIGHLEVEL_CLIENT_ID'),
  HL_CLIENT_SECRET: pick('HL_CLIENT_SECRET', 'HIGHLEVEL_CLIENT_SECRET'),
  ANTHROPIC_API_KEY: pick('ANTHROPIC_API_KEY'),
}
const llmProvider = (pick('LLM_PROVIDER') || 'anthropic').toLowerCase()
if (llmProvider !== 'anthropic') delete required.ANTHROPIC_API_KEY
if (!['anthropic', 'ollama'].includes(llmProvider) && !pick('LLM_API_KEY', 'GEMINI_API_KEY', 'GROQ_API_KEY', 'OPENROUTER_API_KEY'))
  console.warn(`⚠  LLM_PROVIDER=${llmProvider} needs LLM_API_KEY in .env`)
const missing = Object.entries(required).filter(([, v]) => !v).map(([k]) => k)
if (missing.length) console.warn(`⚠  Missing in .env: ${missing.join(', ')} (related features will fail)`)

let encKey = pick('TOKEN_ENCRYPTION_KEY')
if (!encKey) {
  encKey = randomBytes(32).toString('base64')
  appendFileSync(envPath, `\n# Generated by scripts/setup-env.mjs — AES-256 key for OAuth tokens at rest\nTOKEN_ENCRYPTION_KEY=${encKey}\n`)
}

const port = 3000
const write = (rel, lines) => {
  writeFileSync(resolve(root, rel), lines.join('\n') + '\n', { mode: 0o600 })
  console.log(`✓ ${rel}`)
}

write('functions/.env', [
  '# Non-secret runtime config (loaded by Firebase for emulator and deploy).',
  `HL_CLIENT_ID=${required.HL_CLIENT_ID}`,
  `HL_VERSION_ID=${pick('HL_VERSION_ID', 'HIGHLEVEL_VERSION_ID')}`,
  `HL_REDIRECT_URI=http://localhost:${port}/oauth/callback`,
  `FRONTEND_URL=http://localhost:${port}`,
  `ALLOWED_ORIGINS=http://localhost:${port},http://127.0.0.1:${port}`,
  `LLM_PROVIDER=${pick('LLM_PROVIDER') || 'anthropic'}`,
  `LLM_BASE_URL=${pick('LLM_BASE_URL')}`,
  `LLM_MODEL=${pick('LLM_MODEL')}`,
  `LLM_MAX_TOKENS=${pick('LLM_MAX_TOKENS') || '16000'}`,
])
// Emulator-only overrides (.env.local wins over .env.<projectId>, which holds production URLs).
write('functions/.env.local', [
  `HL_REDIRECT_URI=http://localhost:${port}/oauth/callback`,
  `FRONTEND_URL=http://localhost:${port}`,
  `ALLOWED_ORIGINS=http://localhost:${port},http://127.0.0.1:${port}`,
  `LLM_PROVIDER=${llmProvider}`,
  `LLM_BASE_URL=${pick('LLM_BASE_URL')}`,
  `LLM_MODEL=${pick('LLM_MODEL')}`,
])
write('functions/.secret.local', [
  `ANTHROPIC_API_KEY=${required.ANTHROPIC_API_KEY || 'unset'}`,
  `LLM_API_KEY=${pick('LLM_API_KEY', 'GEMINI_API_KEY', 'GROQ_API_KEY', 'OPENROUTER_API_KEY') || 'unset'}`,
  `HL_CLIENT_SECRET=${required.HL_CLIENT_SECRET}`,
  `TOKEN_ENCRYPTION_KEY=${encKey}`,
])
write('frontend/.env.local', [
  ...['API_KEY', 'AUTH_DOMAIN', 'PROJECT_ID', 'STORAGE_BUCKET', 'MESSAGING_SENDER_ID', 'APP_ID'].map(
    (k) => `VITE_FIREBASE_${k}=${pick(`VITE_FIREBASE_${k}`)}`,
  ),
  'VITE_USE_EMULATORS=true',
])
